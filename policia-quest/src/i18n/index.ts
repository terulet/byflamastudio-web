const DICTS: Record<Lang, Dict> = { ca, es }

export function dict(lang: Lang): Dict {
  return DICTS[lang]
}

/**
 * Tria la forma singular o plural.
 *
 * Català i castellà comparteixen la regla que necessitem aquí: singular per a
 * 1 i plural per a la resta, inclòs el zero.
 */
export function plural(n: number, one: string, many: string): string {
  return n === 1 ? one : many
}

/** Substitueix marcadors {clau} d'una cadena traduïda. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  )
}

/** Tria el text en la llengua demanada, amb el català com a alternativa. */
export function pick(value: { ca: string; es?: string }, lang: Lang): string {
  return lang === 'es' && value.es ? value.es : value.ca
}

